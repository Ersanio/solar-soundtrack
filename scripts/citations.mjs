// Checks that every line citation into this repository's own files still points at lines that exist.
// Usage: citations.mjs [--list]
//
// A citation is a file name, a colon and a line or a range of lines, as source comments and the
// guidance (`CLAUDE.md` files, `.claude/**/*.md`) write them. One that names a tracked file must
// fall inside it, and one followed by a declaration's name in brackets must fall inside that
// function, method, class or top-level constant. Citations into AddmusicK's sources are not
// checked: those files are not part of the repository. `--list` prints every citation it resolved.
import { execFileSync } from 'node:child_process';
import console from 'node:console';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Files whose citations are read: the source, and the guidance written for Claude. */
const READ =
  /^((packages\/[^/]+\/src|web\/src|scripts)\/.+\.(ts|mjs|html|css)|(.+\/)?CLAUDE\.md|\.claude\/.+\.md)$/;

/** Generated by the Angular CLI and kept as it emits them. */
const SKIPPED = /^(\.claude\/skills\/angular-|web\/\.claude\/)/;

const CITATION =
  /(?<![\w./-])((?:[\w.@-]+\/)*[\w.-]+\.(?:ts|mjs|js|html|css)):(\d+)(?:-(\d+))?(?!\d|:\d)(?:\s+\(`?([A-Za-z_$][\w$]*)`?\))?/g;

const tracked = execFileSync(
  'git',
  ['ls-files', '-z', '--cached', '--others', '--exclude-standard'],
  {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  },
)
  .split('\0')
  .filter((file) => file !== '' && existsSync(join(root, file)));

const texts = new Map();
const textOf = (file) => {
  if (!texts.has(file)) {
    texts.set(file, readFileSync(join(root, file), 'utf8'));
  }

  return texts.get(file);
};

const lineCount = (file) => textOf(file).split('\n').length;

const declarations = new Map();

/** Every named function, method, class and top-level constant in the file, with the lines it spans. */
function declarationsOf(file) {
  if (declarations.has(file)) {
    return declarations.get(file);
  }

  const found = [];
  const source = ts.createSourceFile(file, textOf(file), ts.ScriptTarget.Latest, true);
  const line = (position) => source.getLineAndCharacterOfPosition(position).line + 1;
  const add = (name, node) => {
    const doc = ts.getJSDocCommentsAndTags(node)[0];
    found.push({ name, from: line((doc ?? node).getStart(source)), to: line(node.getEnd()) });
  };

  const visit = (node, top) => {
    if (
      (ts.isFunctionDeclaration(node) ||
        ts.isClassDeclaration(node) ||
        ts.isMethodDeclaration(node) ||
        ts.isPropertyDeclaration(node) ||
        ts.isGetAccessorDeclaration(node) ||
        ts.isSetAccessorDeclaration(node)) &&
      node.name &&
      ts.isIdentifier(node.name)
    ) {
      add(node.name.text, node);
    } else if (top && ts.isVariableStatement(node)) {
      for (const declaration of node.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name)) {
          add(declaration.name.text, node);
        }
      }
    }

    ts.forEachChild(node, (child) => visit(child, ts.isSourceFile(node)));
  };

  visit(source, false);
  declarations.set(file, found);

  return found;
}

const problems = [];
const resolved = [];
for (const file of tracked.filter((f) => READ.test(f) && !SKIPPED.test(f))) {
  const lines = textOf(file).split('\n');
  for (const [index, text] of lines.entries()) {
    for (const match of text.matchAll(CITATION)) {
      const [whole, cited, first, last, name] = match;
      const targets = tracked.filter((f) => f === cited || f.endsWith(`/${cited}`));
      if (targets.length === 0) {
        continue;
      }

      const from = Number(first);
      const to = last === undefined ? from : Number(last);
      const here = `${file}:${index + 1}`;
      const inside = targets.filter((target) => from >= 1 && to >= from && to <= lineCount(target));
      if (inside.length === 0) {
        const sizes = targets.map((target) => `${target} has ${lineCount(target)} lines`);
        problems.push(`${here}  ${whole}  — ${sizes.join('; ')}`);
        continue;
      }

      resolved.push(`${here}  ${whole}`);
      if (name === undefined) {
        continue;
      }

      const named = inside.flatMap((target) =>
        /\.(ts|mjs|js)$/.test(target) ? declarationsOf(target).filter((d) => d.name === name) : [],
      );
      // A bracketed word that names no declaration is prose, not a claim about one.
      if (named.length > 0 && !named.some((d) => from >= d.from && to <= d.to)) {
        const spans = named.map((d) => `${d.from}-${d.to}`).join(', ');
        problems.push(`${here}  ${whole}  — ${name} is at lines ${spans}`);
      }
    }
  }
}

if (process.argv.includes('--list')) {
  console.log(resolved.join('\n'));
}

if (problems.length > 0) {
  console.error(`${problems.length} line citation(s) point outside what they cite:`);
  console.error(problems.map((problem) => `  ${problem}`).join('\n'));
  process.exit(1);
}

console.log(`citations: ${resolved.length} checked`);
